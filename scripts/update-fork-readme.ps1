# Regenerate the "fork" section at the top of README.md of the main checkout: which upstream commit this
# build is based on and which patches (pr/* branches not merged upstream) are applied on top.
# The section lives between the BEGIN/END markers; it is inserted at the top if the markers are missing.
# Everything else in README.md is left untouched. Run on branch main, after sync-main / prune-merged.
# Usage: .\update-fork-readme.ps1 [-Commit]     (-Commit makes a commit of README.md only)
param([switch]$Commit, [string]$Author = 'guraltsev', [string]$ForkUrl = 'https://github.com/guraltsev/mogan')
$ErrorActionPreference = 'Stop'
# gu_mogan_build has its own git repo; operate on the main checkout.
Set-Location (Split-Path (Split-Path $PSScriptRoot))
if ((git branch --show-current) -ne 'main') { throw "Switch to main first." }
$begin = '<!-- BEGIN FORK PATCHES (generated by gu_mogan_build/scripts/update-fork-readme.ps1; do not edit) -->'
$end   = '<!-- END FORK PATCHES -->'

$baseSha  = (git rev-parse --short upstream-main).Trim()
$baseDate = (git log -1 --format=%cs upstream-main).Trim()
$baseSubj = (git log -1 --format=%s upstream-main).Trim()
$ahead    = [int](git rev-list --count upstream-main..main)

# PR state per branch, from GitHub (squash merges are invisible to git).
$prs = @{}
foreach ($p in (gh pr list --repo MoganLab/mogan --author $Author --state all --limit 200 --json number,headRefName,state,title | ConvertFrom-Json)) {
  if (-not $prs.ContainsKey($p.headRefName) -or $p.state -eq 'OPEN' -or $p.state -eq 'MERGED') { $prs[$p.headRefName] = $p }
}

$rows = @(); $merged = @()
foreach ($b in (git branch --list 'pr/*' --format '%(refname:short)')) {
  $pr = $prs[$b]
  if ($pr -and $pr.state -eq 'MERGED') { $merged += "- [#$($pr.number)](https://github.com/MoganLab/mogan/pull/$($pr.number)) $($pr.title)"; continue }
  # Only patches that are really part of main belong in the list.
  git merge-base --is-ancestor $b main
  if ($LASTEXITCODE) { Write-Warning "$b is not merged into main; skipped"; continue }
  $subj = (git log -1 --format=%s $b).Trim() -replace '^\[[^\]]*\]\s*', ''
  $para = ((git log -1 --format=%b $b) -join "`n") -split "(\r?\n){2}" | Where-Object { $_.Trim() } | Select-Object -First 1
  $desc = if ($para) { ($para -replace '\s*\r?\n\s*', ' ').Trim() } else { '' }
  if ($desc -like 'Co-Authored-By*') { $desc = '' }
  # First sentence only, capped; the full text is in the commit.
  if ($desc -match '^(.+?[.!?])(\s|$)') { $desc = $Matches[1] }
  if ($desc.Length -gt 240) { $desc = $desc.Substring(0, 237).TrimEnd() + '...' }
  # A literal pipe would end the table cell; use the HTML entity.
  $subj = $subj.Replace('|', '&#124;'); $desc = $desc.Replace('|', '&#124;')
  $status = if ($pr -and $pr.state -eq 'OPEN') { "[PR #$($pr.number)](https://github.com/MoganLab/mogan/pull/$($pr.number)) open" }
            elseif ($pr) { "PR #$($pr.number) closed unmerged" } else { 'not submitted' }
  $rows += "| **$subj**<br>$desc | $status | [``$b``]($ForkUrl/tree/$b) |"
}

$md = @()
$md += $begin
$md += '## About this fork: Mogan STEM with extra patches (rolling)'
$md += ''
$md += "This is [MoganLab/mogan](https://github.com/MoganLab/mogan) plus the patches listed below. Clone it and build it as described in the upstream documentation; nothing else differs."
$md += ''
$md += "- **Base:** upstream ``$baseSha`` ($baseDate): $baseSubj"
$md += "- **Patches on top:** $($rows.Count) (``main`` is $ahead commits ahead of the base, including merge commits)"
$md += "- **Branches:** ``main`` = base + patches, append-only (safe to ``git pull``, never force-pushed); ``upstream-main`` = untouched mirror of upstream; ``pr/<name>`` = one patch each, as submitted upstream."
$md += "- **Updated:** $(Get-Date -Format yyyy-MM-dd)"
$md += ''
if ($rows.Count) {
  $md += '| Patch | Upstream status | Branch |'
  $md += '|---|---|---|'
  $md += $rows
  $md += ''
}
if ($merged.Count) {
  $md += '<details><summary>Already merged upstream (no longer patches)</summary>'
  $md += ''
  $md += $merged
  $md += ''
  $md += '</details>'
  $md += ''
}
$md += $end
$section = ($md -join "`n")

$path = Join-Path (Get-Location) 'README.md'
$text = [IO.File]::ReadAllText($path)
$crlf = $text.Contains("`r`n")
$text = $text -replace "`r`n", "`n"
$i = $text.IndexOf($begin); $j = $text.IndexOf($end)
if ($i -ge 0 -and $j -gt $i) { $text = $text.Substring(0, $i) + $section + $text.Substring($j + $end.Length) }
else { $text = $section + "`n`n" + $text }
if ($crlf) { $text = $text -replace "`n", "`r`n" }
[IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding($false)))
Write-Host "README.md updated: base $baseSha, $($rows.Count) patches, $($merged.Count) merged upstream."
if ($Commit) {
  git add README.md
  git commit -m "Update fork section of README (base $baseSha, $($rows.Count) patches)`n`nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>" -- README.md
}
