#!/usr/bin/env bash
# Snapshot the pr/* branches as patch files, generated directly from the branches, into each
# change's own directory: gu_mogan_build/changes/<name>/patches/ (<name> = branch without "pr/").
# Each patches/ folder gets a README.md recording which upstream commit the series applies to, so
# the work stays usable and portable after the branch is deleted.
#
# Usage: scripts/make-patches.sh [BRANCH...]      (default: every local pr/* branch)
#   BASE   env var, default upstream/main: the branch the PRs are meant for
#
# Per branch: `git format-patch --base=<merge-base> <merge-base>..<branch>`. The merge base is the
# upstream commit the series applies to; `--base` also writes it into each patch as a
# `base-commit:` trailer. A branch built on another one yields all its commits.
set -euo pipefail
repo=$(git rev-parse --show-toplevel)
changes="$repo/gu_mogan_build/changes"
base_ref=${BASE:-upstream/main}
if [ $# -gt 0 ]; then branches=("$@"); else
  mapfile -t branches < <(git -C "$repo" for-each-ref --format='%(refname:short)' 'refs/heads/pr/*')
fi
upstream_tip=$(git -C "$repo" rev-parse --short "$base_ref")
for b in "${branches[@]}"; do
  name=${b#pr/}
  [ -d "$changes/$name" ] || { echo "no directory $changes/$name for $b: create it (pr.md, bug.md) first" >&2; exit 1; }
  d="$changes/$name/patches"
  mb=$(git -C "$repo" merge-base "$base_ref" "$b")
  rm -rf "${d:?}"; mkdir -p "$d"
  git -C "$repo" format-patch -q --base="$mb" -o "$d" "$mb..$b"
  n=$(ls "$d" | wc -l)
  cat > "$d/README.md" <<EOF
# Patches for \`$b\`

Generated by \`gu_mogan_build/scripts/make-patches.sh\` on $(date +%F) from the branch; do not edit.
Re-run the script after the branch changes. The branch is the source of truth while it exists; these
files let the work survive if it is deleted, and be ported.

- Patches: $n (apply in file order)
- Branch tip when generated: \`$(git -C "$repo" rev-parse --short "$b")\`
- **Applies on top of upstream commit \`$(git -C "$repo" rev-parse --short "$mb")\`** ($(git -C "$repo" log -1 --format='%cs' "$mb")): $(git -C "$repo" log -1 --format=%s "$mb")
  (full hash \`$mb\`; also in each patch as the \`base-commit:\` trailer). \`$base_ref\` was
  \`$upstream_tip\` at that time.

\`\`\`
git switch -c my-branch $(git -C "$repo" rev-parse --short "$mb")
git am gu_mogan_build/changes/$name/patches/0*.patch
\`\`\`

If the commit is gone or upstream has moved on, apply at the base commit (fetch it from
\`upstream\`) and rebase or cherry-pick from there; \`git am --3way\` helps with small drift.
EOF
  echo "$b -> $d ($n patch(es), base $(git -C "$repo" rev-parse --short "$mb"))"
done
